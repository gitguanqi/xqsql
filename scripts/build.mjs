// xqsql build: 单一 src/ 源码 -> 6 个已发布产物。
// 四个旧路径（lib/xqsql.js、xqsql.min.js、xqsql-esm.js、xqsql-esm.min.js）必须保持不变，
// 因为 CDN 与既有文档引用它们；`.mjs` 是新增镜像，让 Node 不必猜测模块类型。

import { copyFile, mkdir, readFile, stat } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const at = (...parts) => resolve(root, ...parts);

let esbuild;
try {
    esbuild = await import('esbuild');
} catch (error) {
    if (error && error.code === 'ERR_MODULE_NOT_FOUND') {
        console.error('xqsql: 缺少构建依赖。请先运行 `npm install`（需要 esbuild）。');
        process.exit(1);
    }
    throw error;
}

const pkg = JSON.parse(await readFile(at('package.json'), 'utf8'));
const BANNER = `/*! xqsql v${pkg.version} | MIT | generated by scripts/build.mjs — do not edit */\n`;

// esbuild 没有 UMD 输出，用 IIFE 包一层经典 UMD 外壳。
// 根对象写成 self/this 回退，避免 ESM 或严格模式下 `this` 为 undefined 时抛错。
const UMD_HEADER = `(function (root, factory) {
    if (typeof module === 'object' && typeof module.exports === 'object') module.exports = factory();
    else if (typeof define === 'function' && define.amd) define(factory);
    else if (typeof define === 'function' && define.cmd) define(function (require, exports, module) { module.exports = factory(); });
    else root.xqsql = factory();
})(typeof self !== 'undefined' ? self : this, function () {
"use strict";
`;

const UMD_FOOTER = `
return __xqsqlUmd__.default || __xqsqlUmd__;
});
`;

const BUNDLES = [
    { outfile: 'lib/xqsql.js', format: 'iife', umd: true, minify: false },
    { outfile: 'lib/xqsql.min.js', format: 'iife', umd: true, minify: true },
    { outfile: 'lib/xqsql-esm.js', format: 'esm', umd: false, minify: false },
    { outfile: 'lib/xqsql-esm.min.js', format: 'esm', umd: false, minify: true },
];

// `.mjs` 镜像由 `.js` 直接复制，保证两者逐字节相同。
const ESM_MIRRORS = [
    ['lib/xqsql-esm.js', 'lib/xqsql-esm.mjs'],
    ['lib/xqsql-esm.min.js', 'lib/xqsql-esm.min.mjs'],
];

async function buildBundles() {
    for (const bundle of BUNDLES) {
        await esbuild.build({
            entryPoints: [at('src/index.js')],
            outfile: at(bundle.outfile),
            bundle: true,
            format: bundle.format,
            target: ['es2018'],
            minify: bundle.minify,
            charset: 'utf8',
            legalComments: 'none',
            logLevel: 'warning',
            banner: { js: bundle.umd ? BANNER + UMD_HEADER : BANNER },
            ...(bundle.umd ? { globalName: '__xqsqlUmd__', footer: { js: UMD_FOOTER } } : {}),
        });
    }
}

/** 构建不得覆盖手写的类型声明，缺了就只告警（阶段 5 才补）。 */
async function checkTypesPresent() {
    try {
        const declaration = await readFile(at('lib/types/index.d.ts'), 'utf8');
        if (declaration.trim() === '') {
            throw new Error('empty');
        }
    } catch {
        console.warn('xqsql: lib/types/index.d.ts 缺失，types 入口暂不可用。');
    }
}

async function reportSizes() {
    for (const file of [...BUNDLES.map((b) => b.outfile), ...ESM_MIRRORS.map(([, m]) => m)]) {
        const { size } = await stat(at(file));
        console.log(`  ${file.padEnd(26)} ${String(size).padStart(6)} B`);
    }
    console.log(`  ${'lib/types/index.d.ts'.padEnd(26)} ${String((await stat(at('lib/types/index.d.ts')).catch(() => ({ size: 0 }))).size).padStart(6)} B`);
}

await mkdir(at('lib'), { recursive: true });
await buildBundles();
for (const [source, mirror] of ESM_MIRRORS) {
    await copyFile(at(source), at(mirror));
}
await checkTypesPresent();
await reportSizes();
console.log('xqsql: build finished.');
